export const GLOSSARY_TERMS = Object.keys(GLOSSARY);

/** 문장 속 {{용어}} 표시 */
export const TERM_PATTERN = /\{\{([^{}]+)\}\}/g;

/** 문장에서 쓰인 용어 이름 목록 */
export const termsIn = (text: string): string[] => Array.from(text.matchAll(TERM_PATTERN), (m) => m[1]);

/** 표시를 걷어낸 평문. withGloss 가 true 이면 처음 나온 용어 뒤에 (풀이)를 붙인다(음성 읽기·복사용) */
export const plainText = (text: string, withGloss = false, seen: Set<string> = new Set()): string =>
  text.replace(TERM_PATTERN, (_all, term: string) => {
    const entry = GLOSSARY[term];
    if (withGloss && entry && !seen.has(term)) {
      seen.add(term);
      return `${term}(${entry.short})`;
    }
    return term;
  });
