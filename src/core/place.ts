export interface Place {
  id: string;
  name: string;
  region: string;
  /** 동경 기준 경도(도). 서쪽은 음수 */
  lon: number;
  /** IANA 시간대 */
  tz: string;
  /** 국내 여부(호환 모드의 “해외 −30분” 판정용) */
  domestic: boolean;
}

const parse = (region: string, tz: string, domestic: boolean, text: string): Place[] =>
  text
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const i = s.lastIndexOf(' ');
      const name = s.slice(0, i);
      return { id: `${region}-${name}`, name, region, lon: parseFloat(s.slice(i + 1)), tz, domestic };
    });

